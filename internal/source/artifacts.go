package source

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"slices"
	"strings"
)

// GeneratedHeader marks source emitted by gobetter.
const GeneratedHeader = "// Code generated by gobetter; DO NOT EDIT."

// SourceMetadata prefixes the originating source filename in an owned artifact.
const SourceMetadata = "// gobetter:source="

// VersionMetadata prefixes the generator version in an owned artifact.
const VersionMetadata = "// gobetter:version="

// Artifact identifies an owned output and its source and generator version.
type Artifact struct{ Path, Source, Version string }

// InspectArtifact verifies ownership without granting write permission.
func InspectArtifact(path string, data []byte) (Artifact, bool, error) {
	return inspectArtifact(path, data)
}

// OutputFilename keeps known platform suffixes at the end of the sidecar name.
func OutputFilename(source string) string {
	base, suffix := platformFilenameParts(filepath.Base(source))
	return filepath.Join(filepath.Dir(source), base+"_gob"+suffix+".go")
}

func platformFilenameParts(filename string) (base, suffix string) {
	base = strings.TrimSuffix(filename, ".go")
	parts := strings.Split(base, "_")
	oses := "aix android darwin dragonfly freebsd illumos ios js linux netbsd openbsd plan9 solaris wasip1 windows"
	arches := "386 amd64 arm arm64 loong64 mips mipsle mips64 mips64le ppc64 ppc64le riscv64 s390x wasm"
	if len(parts) > 2 && strings.Contains(" "+oses+" ", " "+parts[len(parts)-2]+" ") && strings.Contains(" "+arches+" ", " "+parts[len(parts)-1]+" ") {
		suffix = "_" + strings.Join(parts[len(parts)-2:], "_")
		base = strings.Join(parts[:len(parts)-2], "_")
	} else if len(parts) > 1 && (strings.Contains(" "+oses+" ", " "+parts[len(parts)-1]+" ") || strings.Contains(" "+arches+" ", " "+parts[len(parts)-1]+" ")) {
		suffix = "_" + parts[len(parts)-1]
		base = strings.Join(parts[:len(parts)-1], "_")
	}
	return base, suffix
}

func inspectArtifact(path string, data []byte) (Artifact, bool, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, data, parser.PackageClauseOnly|parser.ParseComments|parser.SkipObjectResolution)
	if err != nil || !file.Package.IsValid() {
		return Artifact{}, false, nil
	}
	var source, version string
	var sourceSeen, versionSeen bool
	header := false
	for _, line := range leadingLineComments(file, data) {
		if line == GeneratedHeader {
			header = true
		}
		if value, ok := strings.CutPrefix(line, SourceMetadata); ok {
			if sourceSeen {
				return Artifact{}, false, fmt.Errorf("duplicate source metadata in %s", path)
			}
			sourceSeen = true
			source = value
		}
		if value, ok := strings.CutPrefix(line, VersionMetadata); ok {
			if versionSeen {
				return Artifact{}, false, fmt.Errorf("duplicate version metadata in %s", path)
			}
			versionSeen = true
			version = value
		}
	}
	if !header || source == "" || version == "" {
		return Artifact{}, false, nil
	}
	if filepath.Base(source) != source || source == "." || !strings.HasSuffix(source, ".go") || strings.HasSuffix(source, "_test.go") {
		return Artifact{}, false, fmt.Errorf("unsafe source metadata in %s", path)
	}
	full := filepath.Join(filepath.Dir(path), source)
	if expected := OutputFilename(full); expected != path {
		return Artifact{}, false, fmt.Errorf("owned output filename does not match source metadata: %s; expected %s; rename or remove the obsolete output before generation", path, expected)
	}
	return Artifact{Path: path, Source: full, Version: version}, true, nil
}

// Legacy formats have the generated header without valid ownership metadata.
// Both the old trailing _gob layout and the platform-preserving layout are
// recognized for diagnostics only; neither grants replacement permission.
func legacyArtifactSource(path string, data []byte) (string, bool) {
	if !bytes.Contains(data, []byte(GeneratedHeader)) {
		return "", false
	}
	file, err := parser.ParseFile(token.NewFileSet(), path, data, parser.PackageClauseOnly|parser.ParseComments|parser.SkipObjectResolution)
	if err != nil || !file.Package.IsValid() {
		return "", false
	}
	if !slices.Contains(leadingLineComments(file, data), GeneratedHeader) {
		return "", false
	}
	if before, ok := strings.CutSuffix(path, "_gob.go"); ok {
		return before + ".go", true
	}
	base, suffix := platformFilenameParts(filepath.Base(path))
	before, ok := strings.CutSuffix(base, "_gob")
	if !ok {
		return "", false
	}
	return filepath.Join(filepath.Dir(path), before+suffix+".go"), true
}

// Only real comment-only // tokens preceding the parsed package clause count.
// Quoted text, block-comment bodies, and trailing comments are not headers.
func leadingLineComments(file *ast.File, data []byte) []string {
	var lines []string
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if comment.End() > file.Package || !strings.HasPrefix(comment.Text, "//") {
				continue
			}
			offset := int(comment.Pos() - file.FileStart)
			start := bytes.LastIndexByte(data[:offset], '\n') + 1
			if len(bytes.TrimSpace(data[start:offset])) == 0 {
				lines = append(lines, comment.Text)
			}
		}
	}
	return lines
}
