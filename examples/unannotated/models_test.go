package main

import (
	"os"
	"strings"
	"testing"
)

func TestExternalConfiguration(t *testing.T) {
	v := NewModelBuilder().Name("upstream").ID("id").Values([2]int{1, 2}).Build()
	if v.ID() != "id" || !v.Equal(v) || !strings.Contains(v.String(), `Name:"upstream"`) {
		t.Fatal(v.String())
	}
	cloned := v
	cloned.Labels = map[string]string{}
	if !v.Equal(cloned) {
		t.Fatal("nil/empty map equality")
	}
	input, err := os.ReadFile("models.go")
	if err != nil || !strings.HasPrefix(string(input), "// Code generated by example upstream; DO NOT EDIT.") || strings.Contains(string(input), "gobetter:struct") {
		t.Fatal("upstream marker/annotation-free contract lost", err)
	}
}
